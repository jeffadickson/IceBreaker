'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const crypto=require('node:crypto'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {LeagueStore}=require('../../server/league-store');
const {RegistrationPortal}=require('../../server/registration-portal');
const {code,match,generateSecret}=require('../../server/mfa-totp');
test('TOTP RFC6238 generates and validates one-time six-digit codes',()=>{
 const secret=generateSecret(),step=123456;
 const value=code(secret,step);
 assert.match(value,/^\d{6}$/);
 assert.equal(match(secret,value,{timeMs:step*30000,lastCounter:step-1}),step);
 assert.equal(match(secret,value,{timeMs:step*30000,lastCounter:step}),null);
 assert.equal(match(secret,'bad',{timeMs:step*30000}),null);
});
test('staff MFA seed encrypted, enabled only after confirmation, old sessions revoked, OTP replay rejected',t=>{
 const previous=process.env.ICEBREAKER_PRIVATE_FIELD_KEY_BASE64;
 process.env.ICEBREAKER_PRIVATE_FIELD_KEY_BASE64=crypto.randomBytes(32).toString('base64');
 t.after(()=>{if(previous===undefined)delete process.env.ICEBREAKER_PRIVATE_FIELD_KEY_BASE64;else process.env.ICEBREAKER_PRIVATE_FIELD_KEY_BASE64=previous;});
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'ib-mfa-')),file=path.join(dir,'league.db');
 const league=new LeagueStore(file,{seedDemo:true}),portal=new RegistrationPortal(file);
 t.after(()=>{portal.close();league.close();fs.rmSync(dir,{recursive:true,force:true});});
 portal.createUser({email:'admin@example.invalid',password:'long-fake-password',role:'LEAGUE_ADMIN',scopeId:'demo-league'});
 const initial=portal.login('admin@example.invalid','long-fake-password');
 const user=portal.authenticate(initial.token);
 const setup=portal.beginMfa(user);
 const row=portal.db.prepare('SELECT mfa_secret FROM registration_users WHERE id=?').get(user.id);
 assert.match(row.mfa_secret,/^enc:v1:/);
 assert.equal(row.mfa_secret.includes(setup.secret),false);
 assert.throws(()=>portal.confirmMfa(user,'000000'),/Invalid MFA/);
 const step=Math.floor(Date.now()/30000);
 assert.deepEqual(portal.confirmMfa(user,code(setup.secret,step)),{enabled:true,signInAgain:true});
 assert.throws(()=>portal.authenticate(initial.token),/sign-in/);
 assert.throws(()=>portal.login('admin@example.invalid','long-fake-password'),/MFA/);
 assert.throws(()=>portal.login('admin@example.invalid','long-fake-password',code(setup.secret,step)),/MFA/);
 const next=code(setup.secret,step+1);
 const login=portal.login('admin@example.invalid','long-fake-password',next);
 assert.equal(portal.authenticate(login.token).role,'LEAGUE_ADMIN');
 assert.throws(()=>portal.login('admin@example.invalid','long-fake-password',next),/MFA/);
});
