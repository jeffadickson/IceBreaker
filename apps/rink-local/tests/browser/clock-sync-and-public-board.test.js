'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {Authority}=require('../../server/authority-sqlite');
const {LeagueStore}=require('../../server/league-store');
const {dailyBoard}=require('../../server/daily-scoreboard');
test('arena sync requires stopped clock and audited reason, without consuming penalty time',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'ib-clock-sync-'));
 const authority=new Authority({dbPath:path.join(dir,'game.sqlite')});
 t.after(()=>{authority.close();fs.rmSync(dir,{recursive:true,force:true});});
 let n=0;const command=c=>authority.command(c,{actor:'rink-clock-operator',key:'sync-test-'+(++n)});
 command({type:'PENALTY_ASSESSED',team:'away',player:'22',infraction:'Tripping',duration:120,classification:'MINOR'});
 const before=authority.spectator().penalties.active[0].remaining;
 command({type:'CLOCK_UPDATED',action:'START',seconds:900});
 assert.throws(()=>command({type:'CLOCK_SYNCED',seconds:850,reason:'Arena camera match'}),/Stop the game clock/);
 command({type:'CLOCK_UPDATED',action:'STOP',seconds:900});
 const remaining=authority.spectator().penalties.active[0].remaining;
 assert.throws(()=>command({type:'CLOCK_SYNCED',seconds:840,reason:''}),/reason/);
 command({type:'CLOCK_SYNCED',seconds:840,reason:'Align with physical rink scoreboard'});
 assert.equal(authority.spectator().seconds,840);
 assert.equal(authority.spectator().penalties.active[0].remaining,remaining);
 assert.equal(authority.spectator().shots.home,0);
 assert.equal(authority.spectator().scores.home,0);
 const audit=fs.readFileSync(authority.auditPath,'utf8');
 assert.match(audit,/CLOCK_SYNCED/);
 const item=authority.state.events.find(e=>e.type==='CLOCK_SYNCED');
 assert.equal(item.details.reason,'Align with physical rink scoreboard');
 assert.equal(item.details.secondsRemaining,840);
 assert.equal(before,120);
});
test('league public scoreboard can be hidden by its administrator without affecting game records',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'ib-public-board-'));
 const dbPath=path.join(dir,'league.sqlite');
 const league=new LeagueStore(dbPath,{seedDemo:true});
 t.after(()=>{league.close();fs.rmSync(dir,{recursive:true,force:true});});
 const day='2026-10-12';
 const first=dailyBoard(league.db,{date:day,leagueId:'demo-league'});
 assert.equal(first.league.publicScoreboardEnabled,true);
 assert.ok(first.divisions.length>=1);
 league.db.prepare("UPDATE leagues SET public_scoreboard_enabled=0 WHERE id='demo-league'").run();
 assert.throws(()=>dailyBoard(league.db,{date:day,leagueId:'demo-league'}),/disabled/);
 assert.equal(league.db.prepare('SELECT COUNT(*) n FROM games').get().n>0,true);
 league.db.prepare("UPDATE leagues SET public_scoreboard_enabled=1 WHERE id='demo-league'").run();
 assert.equal(dailyBoard(league.db,{date:day,leagueId:'demo-league'}).league.id,'demo-league');
 assert.throws(()=>dailyBoard(league.db,{date:day,leagueId:'missing'}),/Unknown league/);
});
