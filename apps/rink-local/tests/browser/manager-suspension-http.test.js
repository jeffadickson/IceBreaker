'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {createRinkServer}=require('../../server/rink-server');
const {LeagueStore}=require('../../server/league-store');
const {TeamAccounts}=require('../../server/team-accounts');
const {gameDate}=require('../../server/player-suspensions');
test('manager receives only own schedule, cannot suspend, and sees suspension eligibility',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'ib-manager-http-')),file=path.join(dir,'game.sqlite');
 const app=createRinkServer({dbPath:file,port:0,operatorKey:'league-admin-secret'});
 const port=(await app.start()).port,base='http://127.0.0.1:'+port;
 const accounts=new TeamAccounts(file),league=new LeagueStore(file);
 t.after(async()=>{accounts.close();league.close();await app.stop();fs.rmSync(dir,{recursive:true,force:true});});
 const g=league.db.prepare("SELECT * FROM games WHERE status='scheduled' ORDER BY date LIMIT 1").get(),team=g.home_team_id;
 const p=accounts.roster(team)[0];
 accounts.createUser('mgr@example.com','password12345678',team);
 const token=accounts.login('mgr@example.com','password12345678').token;
 const schedule=await fetch(base+'/api/team/v1/teams/'+team+'/schedule',{headers:{Authorization:'Bearer '+token}});
 assert.equal(schedule.status,200);
 assert.ok((await schedule.json()).games.some(x=>x.id===g.id));
 const other=await fetch(base+'/api/team/v1/teams/'+g.away_team_id+'/schedule',{headers:{Authorization:'Bearer '+token}});
 assert.equal(other.status,403);
 const date=gameDate(league.db,g.id),payload={playerId:p.id,startDate:date,endDate:date,reason:'League-only disciplinary record'};
 const forbidden=await fetch(base+'/api/league/v1/suspensions',{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify(payload)});
 assert.equal(forbidden.status,403);
 const created=await fetch(base+'/api/league/v1/suspensions',{method:'POST',headers:{'X-Operator-Key':'league-admin-secret','Content-Type':'application/json'},body:JSON.stringify(payload)});
 assert.equal(created.status,201);
 const record=await created.json();
 const lineup=await fetch(base+'/api/team/v1/teams/'+team+'/games/'+g.id+'/lineup',{headers:{Authorization:'Bearer '+token}});
 assert.equal(lineup.status,200);
 const player=(await lineup.json()).players.find(x=>x.id===p.id);
 assert.equal(player.eligible,false);
 assert.equal(player.suspension.reason,undefined);
 const confirmation=await fetch(base+'/api/team/v1/teams/'+team+'/games/'+g.id+'/lineup',{method:'PUT',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({playerIds:[p.id],expectedRosterRevision:0})});
 assert.equal(confirmation.status,400);
 const revoke=await fetch(base+'/api/league/v1/suspensions/'+record.id+'/revoke',{method:'POST',headers:{'X-Operator-Key':'league-admin-secret','Content-Type':'application/json'},body:JSON.stringify({reason:'Appeal upheld'})});
 assert.equal(revoke.status,200);
});
