const pdf=Buffer.from('%PDF-1.7\nfictional-document\n%%EOF\n');
test('AES-GCM envelope roundtrip, wrong AAD and tampering fail authentication',()=>{
 const key=crypto.randomBytes(32),x=seal(pdf,key,'player-1');
 assert.deepEqual(open(x.data,key,x.nonce,x.tag,'player-1'),pdf);
 assert.throws(()=>open(x.data,key,x.nonce,x.tag,'player-2'));
 const tampered=Buffer.from(x.data);tampered[0]^=1;
 assert.throws(()=>open(tampered,key,x.nonce,x.tag,'player-1'));
});
test('quarantine, encryption, scoped document access and verified guardian grant',async t=>{
 const prev=process.env.ICEBREAKER_DOCUMENT_KEK_BASE64;
 process.env.ICEBREAKER_DOCUMENT_KEK_BASE64=crypto.randomBytes(32).toString('base64');
 t.after(()=>{if(prev===undefined)delete process.env.ICEBREAKER_DOCUMENT_KEK_BASE64;else process.env.ICEBREAKER_DOCUMENT_KEK_BASE64=prev;});
 const x=setup(t);
 const playerId=x.portal.createPlayer(x.a,{displayName:'Fictional Alias',legalName:'Fictional Private Name',birthDate:'2016-03-01'}).playerId;
 const personId=x.portal.addRelatedPerson(x.a,playerId,{fullName:'Fictional Guardian',email:'parent@example.invalid',relationship:'GUARDIAN'}).personId;
 const account=x.portal.provisionFamily(x.admin,{personId,email:'parent@example.invalid',password:'family-long-password'});
 assert.ok(account.accountId);
 const family=x.portal.family.authenticate(x.portal.family.login('parent@example.invalid','family-long-password').token);
 assert.equal(x.portal.family.children(family).length,0);
 assert.throws(()=>x.portal.listDocuments(family,playerId),/denied/);
 x.portal.grantGuardian(x.admin,{personId,playerId,canViewDocuments:true,canUploadDocuments:true});
 assert.equal(x.portal.family.children(family).length,1);
 x.portal.family.updateDetails(family,{preferredName:'Fictional Guardian',address:{street:'Fictional Family Street',city:'Demo City'},contactByEmail:true,contactBySms:false});
 assert.equal(x.portal.family.ownContact(family).details.address.city,'Demo City');
 const doc=x.portal.uploadDocument(family,{playerId,documentType:'BIRTH_CERTIFICATE',mime:'application/pdf',base64:pdf.toString('base64')});
 assert.equal(doc.status,'QUARANTINED');
 const raw=fs.readFileSync(x.portal.documents.objectPath(doc.documentId));
 assert.notDeepEqual(raw,pdf);
 assert.equal(raw.includes(Buffer.from('fictional-document')),false);
 assert.throws(()=>x.portal.readDocument(family,doc.documentId),/not available/);
 assert.throws(()=>x.portal.listDocuments(x.b,playerId),/scope/);
 await assert.rejects(()=>x.portal.documents.scanQuarantined(doc.documentId,'test-scanner',async()=>{throw Error('scanner offline');}),/scanner offline/);
 assert.equal(x.portal.documents.row(doc.documentId).status,'QUARANTINED');
 await x.portal.documents.scanQuarantined(doc.documentId,'test-scanner',async()=>({clean:true,engine:'clamav'}));
 assert.deepEqual(x.portal.readDocument(family,doc.documentId).data,pdf);
 assert.deepEqual(x.portal.readDocument(x.a,doc.documentId).data,pdf);
 assert.throws(()=>x.portal.readDocument(x.b,doc.documentId),/scope/);
 x.portal.documentDecision(x.admin,doc.documentId,'VERIFIED','Fictional test reviewed');
 assert.equal(x.portal.listDocuments(family,playerId)[0].status,'VERIFIED');
 x.portal.revokeGuardian(x.admin,{personId,playerId});
 assert.throws(()=>x.portal.readDocument(family,doc.documentId),/denied/);
 assert.deepEqual(x.portal.readDocument(x.a,doc.documentId).data,pdf);
});
