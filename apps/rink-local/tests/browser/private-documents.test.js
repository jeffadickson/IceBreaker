 portal.createUser({email:'a@example.invalid',password:'fictional-long-password',role:'CLUB_REGISTRAR',scopeId:'club-a'});
 portal.createUser({email:'b@example.invalid',password:'fictional-long-password',role:'CLUB_REGISTRAR',scopeId:'club-b'});
